#!/usr/bin/env python3
"""Plot h_N heatmaps over r_mu and r_f for N=16, 64, and 256.

This script reads the Monte Carlo surface data generated by
plot_hN_surface_ru_rf.py and renders a publication-style 2D small-multiple
heatmap. The purpose is to make the downward shift of h_N with increasing block
length visually legible.
"""

import argparse
from pathlib import Path
import csv
import sys

import numpy as np
import matplotlib.pyplot as plt
import matplotlib.patheffects as pe
from matplotlib.ticker import FormatStrFormatter


SCRIPT_DIR = Path(__file__).resolve().parent
ARTIFACT_DIR = SCRIPT_DIR.parent
ARTIFACT_ROOT = SCRIPT_DIR.parents[2]
sys.path.insert(0, str(ARTIFACT_ROOT))
from figure_style import LINE_WIDTHS, apply_arial_style, manuscript_width
DEFAULT_INPUT = ARTIFACT_DIR / "data" / "derived" / "hN_surface_rmu_rf_N_shifted_fs100M.csv"
DEFAULT_OUTPUT = ARTIFACT_DIR / "figure" / "fig07_hn_heatmap_shifted.pdf"


def load_surfaces(path: Path):
    with path.open("r", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise ValueError(f"No data rows in {path}")

    rmu_values = np.array(sorted({float(row["r_mu"]) for row in rows}))
    rf_values = np.array(sorted({float(row["r_f"]) for row in rows}))
    rmu_index = {v: i for i, v in enumerate(rmu_values)}
    rf_index = {v: i for i, v in enumerate(rf_values)}

    surfaces = {}
    for row in rows:
        n = int(row["N"])
        surfaces.setdefault(n, np.empty((len(rf_values), len(rmu_values)), dtype=float))
        i = rf_index[float(row["r_f"])]
        j = rmu_index[float(row["r_mu"])]
        surfaces[n][i, j] = float(row["h_N"])
    return rmu_values, rf_values, dict(sorted(surfaces.items()))


def plot_level_heatmaps(rmu_values, rf_values, surfaces, output: Path):
    apply_arial_style()
    fig = plt.figure(figsize=(manuscript_width(1.0), 1.85))
    gs = fig.add_gridspec(1, 4, width_ratios=[1, 1, 1, 0.05], wspace=0.16)
    axes = [fig.add_subplot(gs[0, i]) for i in range(3)]
    cax = fig.add_subplot(gs[0, 3])
    extent = [rmu_values.min(), rmu_values.max(), rf_values.min(), rf_values.max()]

    images = []
    for ax, (n, h) in zip(axes, surfaces.items()):
        im = ax.imshow(
            h,
            origin="lower",
            extent=extent,
            aspect="auto",
            interpolation="nearest",
            cmap="viridis",
            vmin=0.0,
            vmax=1.0,
        )
        images.append(im)
        levels = np.linspace(0.2, 0.8, 4)
        cs = ax.contour(rmu_values, rf_values, h, levels=levels, colors="white", linewidths=LINE_WIDTHS["secondary"], alpha=0.9)
        labels = ax.clabel(cs, fmt="%.1f", inline=True, inline_spacing=1, colors="white")
        for label in labels:
            x, y = label.get_position()
            near_edge = x > rmu_values.max() - 0.03 or y > rf_values.max() - 0.03
            if near_edge:
                label.set_visible(False)
            else:
                label.set_path_effects([pe.withStroke(linewidth=LINE_WIDTHS["marker_edge"], foreground="black")])
        if n == 256:
            manual_labels = ax.clabel(
                cs,
                levels=[0.2],
                manual=[(0.50, 0.36)],
                fmt="%.1f",
                inline=True,
                inline_spacing=1,
                colors="white",
            )
            for label in manual_labels:
                label.set_path_effects([pe.withStroke(linewidth=LINE_WIDTHS["marker_edge"], foreground="black")])
        ax.set_title(rf"$N={n}$")
        ax.set_xlabel(r"$r_\mu$")
        ax.xaxis.set_major_formatter(FormatStrFormatter("%.1f"))
        ax.yaxis.set_major_formatter(FormatStrFormatter("%.1f"))
        ax.tick_params(length=3, width=LINE_WIDTHS["axis"])
    axes[0].set_ylabel(r"$r_f$")
    for ax in axes[1:]:
        ax.tick_params(labelleft=False)

    cbar = fig.colorbar(images[-1], cax=cax)
    cbar.set_label(r"$h_N$")
    fig.subplots_adjust(left=0.08, right=0.91, bottom=0.24, top=0.85)
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description="Plot shifted-power conditional min-entropy heatmaps.")
    parser.add_argument("--csv", type=Path, default=DEFAULT_INPUT, help="Archived h_N surface CSV.")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT, help="Main heatmap PDF output.")
    args = parser.parse_args()
    rmu_values, rf_values, surfaces = load_surfaces(args.csv)
    plot_level_heatmaps(rmu_values, rf_values, surfaces, args.out)
    print(f"Wrote {args.out.resolve()}")


if __name__ == "__main__":
    main()
