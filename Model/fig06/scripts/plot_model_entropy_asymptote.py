#!/usr/bin/env python3
"""Plot conditional min-entropy versus sampling frequency with asymptotes.

This script is intentionally plot-only. It reads the Monte Carlo results
generated by compute_block_entropy_vs_fs.py and redraws the paper figure so
that the low-frequency and high-frequency envelope limits are visually clear.
"""

import argparse
import csv
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

ARTIFACT_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ARTIFACT_ROOT))
from figure_style import LEGEND_STYLE, LINE_WIDTHS, apply_arial_style, manuscript_width


def read_rows(path: Path):
    with path.open(newline="") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise ValueError(f"No rows found in {path}")

    required = {
        "fs_hz",
        "hmin_per_bit_mc",
        "h_upper_independent",
        "h_under_shared",
    }
    missing = required.difference(rows[0])
    if missing:
        raise ValueError(f"{path} is missing columns: {sorted(missing)}")
    return sorted(rows, key=lambda row: float(row["fs_hz"]))


def closest_index(values: np.ndarray, target: float) -> int:
    return int(np.argmin(np.abs(np.log(values) - np.log(target))))


def main() -> None:
    script_dir = Path(__file__).resolve().parent
    artifact_dir = script_dir.parent
    parser = argparse.ArgumentParser(
        description="Redraw h_N versus fs with independent/shared flicker asymptotes."
    )
    parser.add_argument(
        "--csv",
        type=Path,
        default=artifact_dir / "data" / "derived" / "block_entropy_shifted.csv",
        help="CSV produced by compute_block_entropy_vs_fs.py.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=artifact_dir / "figure" / "fig06_model_entropy_vs_fs_shifted.pdf",
        help="PDF output path.",
    )
    parser.add_argument(
        "--png",
        type=Path,
        default=artifact_dir / "figure" / "fig06_model_entropy_vs_fs_shifted.png",
        help="PNG preview output path.",
    )
    parser.add_argument("--low-fs", type=float, default=1e6, help="Low-frequency marker.")
    parser.add_argument("--high-fs", type=float, default=1e9, help="High-frequency marker.")
    args = parser.parse_args()

    rows = read_rows(args.csv)
    fs = np.array([float(row["fs_hz"]) for row in rows])
    h_mc = np.array([float(row["hmin_per_bit_mc"]) for row in rows])
    upper = np.array([float(row["h_upper_independent"]) for row in rows])
    lower = np.array([float(row["h_under_shared"]) for row in rows])
    block_len = int(float(rows[0].get("block_len", 1)))

    if "hmin_mc_se" in rows[0]:
        # The source script stores the standard error of the block entropy.
        yerr = np.array([float(row["hmin_mc_se"]) for row in rows]) / max(block_len, 1)
    else:
        yerr = None

    low_idx = closest_index(fs, args.low_fs)
    high_idx = closest_index(fs, args.high_fs)
    upper_level = float(np.nanmean(upper))
    lower_level = float(np.nanmean(lower))

    apply_arial_style()
    fig, ax = plt.subplots(figsize=(manuscript_width(0.95), 2.40))

    ax.fill_between(
        fs,
        lower,
        upper,
        color="#1F77B4",
        alpha=0.08,
        linewidth=0,
        label="Envelope",
    )
    ax.semilogx(
        fs,
        upper,
        color="#1F77B4",
        linestyle="--",
        linewidth=LINE_WIDTHS["primary"],
        label="Independent limit",
    )
    ax.semilogx(
        fs,
        lower,
        color="#D55E00",
        linestyle="--",
        linewidth=LINE_WIDTHS["primary"],
        label="Shared limit",
    )
    ax.errorbar(
        fs,
        h_mc,
        yerr=yerr,
        color="#202020",
        marker="o",
        markersize=5.0,
        linewidth=LINE_WIDTHS["primary"],
        elinewidth=LINE_WIDTHS["secondary"],
        capsize=2.0,
        zorder=3,
        label=r"Monte Carlo $h_N$",
    )

    for idx, color in [(low_idx, "#1F77B4"), (high_idx, "#D55E00")]:
        ax.axvline(fs[idx], color=color, linestyle=":", linewidth=LINE_WIDTHS["secondary"], alpha=0.75)
        ax.scatter(fs[idx], h_mc[idx], s=32, color=color, edgecolor="white", linewidth=LINE_WIDTHS["marker_edge"], zorder=4)

    ax.set_xlabel(r"Sampling frequency $f_s$ (Hz)")
    ax.set_ylabel(r"Per-bit conditional min-entropy $h_N$")
    ax.set_xlim(fs[0] * 0.82, fs[-1] * 1.18)
    ax.set_ylim(max(0.0, lower_level - 0.055), min(1.0, upper_level + 0.075))
    ax.set_xticks([1e6, 1e7, 1e8, 1e9])
    ax.set_xticklabels([r"$10^6$", r"$10^7$", r"$10^8$", r"$10^9$"])
    ax.grid(True, which="major", color="#D9D9D9", linestyle="-", linewidth=LINE_WIDTHS["grid"], alpha=0.75)
    ax.grid(True, which="minor", color="#E8E8E8", linestyle="-", linewidth=LINE_WIDTHS["grid"], alpha=0.55)
    ax.tick_params(width=LINE_WIDTHS["axis"], length=3)
    legend_style = dict(LEGEND_STYLE)
    legend_style.update(
        {
            "loc": "upper center",
            "bbox_to_anchor": (0.5, 1.085),
            "ncol": 4,
            "handletextpad": 0.4,
            "borderaxespad": 0.0,
        }
    )
    ax.legend(**legend_style)

    fig.subplots_adjust(left=0.14, right=0.99, bottom=0.21, top=0.88)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(args.out, bbox_inches="tight", pad_inches=0.02)
    if args.png:
        args.png.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(args.png, dpi=300, bbox_inches="tight", pad_inches=0.02)
    print(f"Wrote {args.out.resolve()}")
    if args.png:
        print(f"Wrote {args.png.resolve()}")


if __name__ == "__main__":
    main()
